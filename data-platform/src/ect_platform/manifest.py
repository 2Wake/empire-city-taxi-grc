"""Build-tools manifest: the software components the data platform runs on (POL-10 statements 1 and 4;
PCI DSS 6.3.2; GOV-160).

    uv run ect-manifest           # rewrite build-tools-manifest.md
    uv run ect-manifest --check   # exit 1 if the file is out of date (a test runs this on every change)

Lists Python and every locked package (uv.lock), the dbt pins and every GitHub Action the workflows use.
ECT has no servers of its own, so with the SaaS vendors in DOC-03 this is the whole software inventory.
The file has no date in it, so it only changes when a component changes; git history dates each change.
"""
import argparse
import re
import sys
import tomllib

from .config import GENERATOR_VERSION, ROOT

REPO = ROOT.parent
MANIFEST_PATH = ROOT / "build-tools-manifest.md"
WORKFLOWS = REPO / ".github" / "workflows"


def build() -> str:
    lock = tomllib.loads((ROOT / "uv.lock").read_text())
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())
    direct = {re.split(r"[<>=!~\[ ;]", d, 1)[0].lower() for d in project["project"].get("dependencies", [])}
    for group in project.get("dependency-groups", {}).values():
        direct |= {re.split(r"[<>=!~\[ ;]", d, 1)[0].lower() for d in group if isinstance(d, str)}
    lines = ["# Build-tools manifest", "",
             "Software components of the ECT data platform (POL-10 statements 1 and 4; PCI DSS 6.3.2).",
             "Generated by `uv run ect-manifest`; a test fails if it is out of date. Do not edit by hand.", "",
             f"- Generator version: {GENERATOR_VERSION}",
             f"- Python: {lock.get('requires-python', project['project'].get('requires-python', '?'))} (run through uv)", "",
             "## GitHub Actions", "", "| Workflow | Action | Version |", "|---|---|---|"]
    for wf in sorted(WORKFLOWS.glob("*.yml")):
        for name, ver in sorted(set(re.findall(r"uses:\s*([\w./-]+)@([\w.-]+)", wf.read_text()))):
            lines.append(f"| `{wf.name}` | `{name}` | `{ver}` |")
    lines += ["", "## dbt (pinned in the daily workflow)", "", "| Package | Version |", "|---|---|"]
    pins = sorted(set(re.findall(r"(dbt-[a-z]+)==([\d.]+)", (WORKFLOWS / "daily-refresh.yml").read_text())))
    lines += [f"| `{n}` | `{v}` |" for n, v in pins]
    lines += ["", "## Python packages (uv.lock)", "",
              "Direct dependencies are marked; the rest are installed because a direct dependency needs them.", "",
              "| Package | Version | Direct |", "|---|---|---|"]
    for p in sorted(lock["package"], key=lambda p: p["name"]):
        if p.get("source", {}).get("editable") or p.get("source", {}).get("virtual"):
            continue
        lines.append(f"| `{p['name']}` | `{p.get('version', '?')}` | {'yes' if p['name'].lower() in direct else ''} |")
    lines += ["", "## Command-line tools (maintainer's machine)", "",
              "`gcloud` and `bq` (Google Cloud SDK) and `gh` are used for read-only checks and setup. They aren't part",
              "of the daily run, and their versions aren't pinned.", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = build()
    if args.check:
        current = MANIFEST_PATH.read_text() if MANIFEST_PATH.exists() else ""
        if current != text:
            print("build-tools-manifest.md is out of date: run `uv run ect-manifest`.")
            return 1
        print("build-tools-manifest.md is up to date.")
        return 0
    MANIFEST_PATH.write_text(text)
    print(f"Wrote {MANIFEST_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
